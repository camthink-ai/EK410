#!/usr/bin/env python3
"""Build a compact 4bpp CamThink logo asset for the EK410 splash module.

Brand PNG is dark-grey + orange on transparent. E-ink remaps (white bg):
  ink (charcoal) → BLACK (0x0)
  orange accents → RED   (0x3)
  transparent    → WHITE (0x1)  (panel splash bg also WHITE)

Uses a palette image + NEAREST resize so anti-alias cannot wipe the ink.

Usage:
  python3 tools/gen_splash_logo.py assets/brand/CamThink_LOGO.png -o main/splash_logo_data.h
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

BLACK, WHITE, RED = 0x0, 0x1, 0x3
TARGET_MAX_W = 1100


def ink_code(r: int, g: int, b: int, a: int) -> int:
    if a < 32:
        return WHITE  # transparent → white panel
    # Brand orange
    if r >= 150 and g < 160 and b < 100 and r > (g + 40):
        return RED
    # Wordmark ink → black on white
    if a >= 32:
        return BLACK
    return WHITE


def convert(src: Path, max_w: int) -> tuple[int, int, bytes]:
    im = Image.open(src).convert("RGBA")
    w, h = im.size
    px = im.load()

    # Palette RGB: white bg / black ink / red accents.
    hard = Image.new("RGB", (w, h), (255, 255, 255))
    hp = hard.load()
    xs, ys = [], []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            c = ink_code(r, g, b, a)
            if c == BLACK:
                hp[x, y] = (0, 0, 0)
                xs.append(x)
                ys.append(y)
            elif c == RED:
                hp[x, y] = (255, 40, 0)
                xs.append(x)
                ys.append(y)

    if not xs:
        raise SystemExit("no logo ink pixels found — check source alpha")

    pad = 4
    x0 = max(0, min(xs) - pad)
    y0 = max(0, min(ys) - pad)
    x1 = min(w, max(xs) + 1 + pad)
    y1 = min(h, max(ys) + 1 + pad)
    cropped = hard.crop((x0, y0, x1, y1))
    cw, ch = cropped.size

    scale = min(1.0, max_w / float(cw))
    out_w = int(round(cw * scale))
    out_h = int(round(ch * scale))
    out_w -= out_w % 2
    if out_w < 2:
        out_w = 2
    if out_h < 1:
        out_h = 1

    # NEAREST keeps hard edges / palette.
    scaled = cropped.resize((out_w, out_h), Image.Resampling.NEAREST)
    sp = scaled.load()

    buf = bytearray((out_w * out_h) // 2)
    black_n = red_n = 0
    for y in range(out_h):
        for bx in range(out_w // 2):
            def code_at(xx: int) -> int:
                r, g, b = sp[xx, y]
                if r > 150 and g < 120 and b < 80:
                    return RED
                if r < 40 and g < 40 and b < 40:
                    return BLACK
                return WHITE

            hi = code_at(bx * 2)
            lo = code_at(bx * 2 + 1)
            if hi == BLACK:
                black_n += 1
            if lo == BLACK:
                black_n += 1
            if hi == RED:
                red_n += 1
            if lo == RED:
                red_n += 1
            buf[y * (out_w // 2) + bx] = (hi << 4) | lo

    print(f"ink stats: black={black_n} red={red_n} white={out_w * out_h - black_n - red_n}")
    if black_n < 100:
        raise SystemExit(f"too little black ink ({black_n}) — refusing bad asset")
    return out_w, out_h, bytes(buf)


def emit_header(path: Path, w: int, h: int, data: bytes, src_name: str) -> None:
    lines = [
        "/* Auto-generated by tools/gen_splash_logo.py — do not edit. */",
        f"/* source: {src_name}  size: {w}x{h}  bytes: {len(data)} */",
        "#ifndef SPLASH_LOGO_DATA_H",
        "#define SPLASH_LOGO_DATA_H",
        "",
        f"#define SPLASH_LOGO_W {w}",
        f"#define SPLASH_LOGO_H {h}",
        f"#define SPLASH_LOGO_BYTES {len(data)}",
        "",
        "static const unsigned char SPLASH_LOGO_BITS[SPLASH_LOGO_BYTES] = {",
    ]
    row = "  "
    for i, b in enumerate(data):
        row += f"0x{b:02X},"
        if (i + 1) % 16 == 0:
            lines.append(row)
            row = "  "
        else:
            row += " "
    if row.strip():
        lines.append(row.rstrip())
    lines += ["};", "", "#endif /* SPLASH_LOGO_DATA_H */", ""]
    path.write_text("\n".join(lines))
    print(f"wrote {path} ({w}x{h}, {len(data)} bytes)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", default="main/splash_logo_data.h")
    ap.add_argument("--max-w", type=int, default=TARGET_MAX_W)
    args = ap.parse_args()
    src = Path(args.input)
    w, h, data = convert(src, args.max_w)
    emit_header(Path(args.o), w, h, data, src.name)


if __name__ == "__main__":
    main()
