#!/usr/bin/env python3
"""Convert main/www/index.html into main/www_html.h (gzip-compressed blob).

Serving ~200KB+ uncompressed HTML over STA while MQTT is up exhausts ESP32-C61
Wi-Fi TX buffers (wifi:mem fail → httpd accept 113 → panic/reboot). Gzip cuts
the wire size ~3–4x so the SoftAP/LAN page can load without killing the stack.
"""
import gzip
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "main", "www", "index.html")
QRJS = os.path.join(ROOT, "main", "www", "qrcodegen.min.js")
DST = os.path.join(ROOT, "main", "www_html.h")

html = open(SRC, encoding="utf-8").read()
# SoftAP has no CDN — embed Nayuki qrcodegen before the page script.
if os.path.isfile(QRJS) and "<script>" in html:
    qr = open(QRJS, encoding="utf-8").read().strip()
    html = html.replace("<script>", "<script>\n/* qrcodegen (Nayuki) */\n" + qr + "\n", 1)

raw = html.encode("utf-8")
# Fixed mtime so rebuilds are bit-identical when HTML is unchanged.
_buf = io.BytesIO()
with gzip.GzipFile(fileobj=_buf, mode="wb", compresslevel=9, mtime=0) as _gz:
    _gz.write(raw)
gz = _buf.getvalue()

with open(DST, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/gen_www.py — do not edit; edit www/index.html instead.\n")
    f.write("#ifndef WWW_HTML_H\n#define WWW_HTML_H\n\n")
    f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write("/* Uncompressed HTML length (informational). */\n")
    f.write("static const size_t INDEX_HTML_RAW_LEN = %d;\n\n" % len(raw))
    f.write("static const size_t INDEX_HTML_GZ_LEN = %d;\n" % len(gz))
    f.write("static const uint8_t INDEX_HTML_GZ[] = {\n")
    for i in range(0, len(gz), 16):
        chunk = gz[i : i + 16]
        f.write("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
    f.write("};\n\n")
    f.write("#endif\n")

print(
    "wrote %s (html=%d gzip=%d ratio=%.2f)"
    % (DST, len(raw), len(gz), len(raw) / max(len(gz), 1))
)
