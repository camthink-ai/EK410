#!/usr/bin/env python3
"""Generate main/font_hz16.c + .h — 16x16 CJK glyphs (GB2312 repertoire)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_PATHS = [
    "/System/Library/Fonts/Hiragino Sans GB.ttc",
    "/System/Library/Fonts/STHeiti Light.ttc",
]


def pack16(im: Image.Image) -> bytes:
    px = im.load()
    out = bytearray(32)
    for y in range(16):
        row = 0
        for x in range(16):
            if px[x, y][0] < 128:
                row |= 0x8000 >> x
        out[y * 2] = (row >> 8) & 0xFF
        out[y * 2 + 1] = row & 0xFF
    return bytes(out)


def main() -> None:
    font = None
    for p in FONT_PATHS:
        try:
            font = ImageFont.truetype(p, 15, index=0)
            break
        except OSError:
            continue
    if font is None:
        raise SystemExit("no CJK TTF found")

    glyphs = []
    seen = set()
    for qu in range(0xA1, 0xF8):
        for wei in range(0xA1, 0xFF):
            try:
                ch = bytes([qu, wei]).decode("gb2312")
            except Exception:
                continue
            if not ch or ch in seen:
                continue
            u = ord(ch)
            if u < 0x80:
                continue
            seen.add(ch)
            im = Image.new("RGB", (16, 16), (255, 255, 255))
            ImageDraw.Draw(im).text((0, -1), ch, font=font, fill=(0, 0, 0))
            glyphs.append((u, pack16(im)))

    glyphs.sort(key=lambda t: t[0])
    (ROOT / "main/font_hz16.h").write_text(
        """#ifndef FONT_HZ16_H
#define FONT_HZ16_H
#include <stdint.h>
#include <stdbool.h>

#define HZ16_W 16
#define HZ16_H 16

#ifdef __cplusplus
extern "C" {
#endif

int hz16_glyph_count(void);
bool hz16_lookup(uint16_t unicode, uint8_t out[32]);

#ifdef __cplusplus
}
#endif
#endif
"""
    )
    out = ROOT / "main/font_hz16.c"
    with out.open("w") as f:
        f.write("/* Auto-generated by tools/gen_font_hz.py — do not edit. */\n")
        f.write('#include "font_hz16.h"\n\n')
        f.write(f"#define HZ16_N {len(glyphs)}\n")
        f.write("static const uint16_t s_hz_u[HZ16_N] = {\n")
        for i, (u, _) in enumerate(glyphs):
            f.write(f" 0x{u:04X},")
            if (i + 1) % 12 == 0:
                f.write("\n")
        f.write("\n};\n")
        f.write("static const uint8_t s_hz_bits[HZ16_N][32] = {\n")
        for _, bits in glyphs:
            f.write(" {" + ",".join(f"0x{b:02X}" for b in bits) + "},\n")
        f.write("};\n\n")
        f.write(
            "int hz16_glyph_count(void) { return HZ16_N; }\n\n"
            "bool hz16_lookup(uint16_t unicode, uint8_t out[32])\n"
            "{\n"
            "    int lo = 0, hi = HZ16_N - 1;\n"
            "    while (lo <= hi) {\n"
            "        int mid = (lo + hi) >> 1;\n"
            "        uint16_t v = s_hz_u[mid];\n"
            "        if (v == unicode) {\n"
            "            for (int i = 0; i < 32; i++) out[i] = s_hz_bits[mid][i];\n"
            "            return true;\n"
            "        }\n"
            "        if (v < unicode) lo = mid + 1;\n"
            "        else hi = mid - 1;\n"
            "    }\n"
            "    return false;\n"
            "}\n"
        )
    print(f"wrote {out} glyphs={len(glyphs)} size={out.stat().st_size}")


if __name__ == "__main__":
    main()
