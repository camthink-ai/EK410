#!/usr/bin/env python3
"""Generate main/font8x16.h — 8x16 ASCII bitmaps (32..126).

Source font: Noto Sans Mono CJK SC Regular (SIL Open Font License 1.1) —
the monospace companion of the CJK font in font_hz16.c, so Latin and CJK
text share one design. At 16 px every ASCII glyph is exactly 8 px wide,
which is the cell this firmware uses.
Verified input: Version 2.004,
  sha256 ec04cc376b34887cedbdf84074e2e226ed2761eeabdcb9173fc1dd7bfd153ef7
The 16 MB font is not committed — point EK410_MONO_FONT at a copy, or put
one in assets/fonts/:
  https://github.com/notofonts/noto-cjk  (Sans/Mono/)

Raster: 16 px, drawn on the baseline at row BASELINE_ROW (descenders end on
the last row), binarised at threshold 128 (Regular weight stays 1 px wide,
matching the CJK table).

Usage: python3 tools/gen_font.py [OUTPUT]   (default main/font8x16.h)
"""
import hashlib
import os
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_NAME = "Noto Sans Mono CJK SC"
FONT_SHA256 = "ec04cc376b34887cedbdf84074e2e226ed2761eeabdcb9173fc1dd7bfd153ef7"
FONT_CANDIDATES = [
    os.environ.get("EK410_MONO_FONT", ""),
    str(ROOT / "assets/fonts/NotoSansMonoCJKsc-Regular.otf"),
]
W, H = 8, 16
FIRST, LAST = 32, 126
SIZE, BASELINE_ROW, THRESHOLD = 16, 12, 128


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "main/font8x16.h"
    path = next((p for p in FONT_CANDIDATES if p and Path(p).is_file()), None)
    if path is None:
        raise SystemExit(f"{FONT_NAME} not found: set EK410_MONO_FONT=<path to "
                         "NotoSansMonoCJKsc-Regular.otf>")
    digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()
    if digest != FONT_SHA256:
        print(f"warning: {path}\n  sha256 {digest}\n  differs from the verified "
              f"input {FONT_SHA256} — glyphs may differ from the committed table",
              file=sys.stderr)
    font = ImageFont.truetype(path, SIZE)
    if font.getname()[0] != FONT_NAME:
        raise SystemExit(f"{path} is {font.getname()[0]}, expected {FONT_NAME}")

    glyphs = []
    for ch in range(FIRST, LAST + 1):
        # Anchor "ls": x = left edge, y = baseline — independent of the font's
        # ascender metric, which is sized for CJK and far above Latin caps.
        g = Image.new("L", (W, H), 255)
        ImageDraw.Draw(g).text((0, BASELINE_ROW), chr(ch), font=font, anchor="ls", fill=0)
        px = g.load()
        rows = []
        for y in range(H):
            b = 0
            for x in range(W):
                b = (b << 1) | (1 if px[x, y] < THRESHOLD else 0)
            rows.append(b)
        glyphs.append(rows)

    with out.open("w") as f:
        f.write("// Auto-generated by tools/gen_font.py — 8x16 ASCII %d..%d\n" % (FIRST, LAST))
        f.write("// Source font: Noto Sans Mono CJK SC Regular, SIL OFL 1.1.\n")
        f.write("#ifndef FONT8X16_H\n#define FONT8X16_H\n\n")
        f.write("#define FONT_FIRST %d\n#define FONT_LAST %d\n#define FONT_W %d\n#define FONT_H %d\n\n"
                % (FIRST, LAST, W, H))
        f.write("static const unsigned char font8x16[%d][%d] = {\n" % (len(glyphs), H))
        for rows in glyphs:
            f.write("    {" + ", ".join("0x%02X" % r for r in rows) + "},\n")
        f.write("};\n#endif\n")
    blank = [chr(FIRST + i) for i, rows in enumerate(glyphs) if not any(rows)]
    print("wrote %s (%d glyphs) font=%s %dpx baseline_row=%d thr=%d blank=%s"
          % (out, len(glyphs), font.getname()[0], SIZE, BASELINE_ROW, THRESHOLD,
             "".join(blank)))


if __name__ == "__main__":
    main()
