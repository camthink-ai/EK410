#!/usr/bin/env python3
"""Generate font8x16.h from a macOS monospace font (ASCII 32..126)."""
from PIL import Image, ImageDraw, ImageFont
import sys

FONT_PATH = "/System/Library/Fonts/Menlo.ttc"
OUT = sys.argv[1] if len(sys.argv) > 1 else "main/font8x16.h"

W, H = 8, 16
FIRST, LAST = 32, 126
font = ImageFont.truetype(FONT_PATH, 12)

glyphs = []
for ch in range(FIRST, LAST + 1):
    img = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 1), chr(ch), font=font, fill=1)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            b = (b << 1) | (1 if img.getpixel((x, y)) else 0)
        rows.append(b)
    glyphs.append(rows)

with open(OUT, "w") as f:
    f.write("// Auto-generated by tools/gen_font.py — 8x16 ASCII %d..%d\n" % (FIRST, LAST))
    f.write("#ifndef FONT8X16_H\n#define FONT8X16_H\n\n")
    f.write("#define FONT_FIRST 32\n#define FONT_LAST 126\n#define FONT_W 8\n#define FONT_H 16\n\n")
    f.write("static const unsigned char font8x16[%d][%d] = {\n" % (len(glyphs), H))
    for rows in glyphs:
        f.write("    {" + ", ".join("0x%02X" % r for r in rows) + "},\n")
    f.write("};\n#endif\n")
print("wrote %s (%d glyphs)" % (OUT, len(glyphs)))
